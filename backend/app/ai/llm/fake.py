from typing import Any, Optional

from app.ai.llm.base import LLMMessage, LLMProvider, LLMResponse


class FakeLLMProvider(LLMProvider):
    """
    Deterministic fake LLM provider for offline testing.
    Supports scripted responses, call inspection, and configurable failures.
    """

    def __init__(
        self,
        responses: Optional[list[str] | str] = None,
        failures: Optional[list[Exception] | Exception] = None,
        model: str = "fake-model",
    ):
        if isinstance(responses, str):
            self.responses = [responses]
        elif responses is not None:
            self.responses = list(responses)
        else:
            self.responses = []

        if isinstance(failures, Exception):
            self.failures = [failures]
        elif failures is not None:
            self.failures = list(failures)
        else:
            self.failures = []

        self.model = model
        self.calls: list[dict[str, Any]] = []

    async def complete(
        self,
        messages: list[LLMMessage],
        temperature: float = 0.0,
        max_tokens: int = 512,
    ) -> LLMResponse:
        self.calls.append({
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        })

        if self.failures:
            exc = self.failures.pop(0)
            raise exc

        if self.responses:
            content = self.responses.pop(0)
        else:
            content = "This is a deterministic test summary generated by FakeLLMProvider."

        return LLMResponse(
            content=content,
            model=self.model,
            prompt_tokens=100,
            completion_tokens=50,
        )
